SELECT
	a.UTBILDNINGSNAMN AS education_title,
        (SUM(a.BEVILJADE_PLATSER_TOTALT)) AS approved_applications
FROM ANSOKAN a
	JOIN SUN5_INRIKTNING b ON b.SUN5_ID = a.SUN5_ID
	JOIN UTBILDNINGSOMRADE c ON c.UTBILDNINGSOMRADE_ID = b.UTBILDNINGSOMRADE_ID
WHERE c.UTBILDNINGSOMRADE = 'Data/IT' AND a.BESLUT = 'Beviljad'
	AND a.UTBILDNINGSNAMN LIKE '%Data%'
   	OR a.UTBILDNINGSNAMN LIKE '%IT%'
GROUP BY c.UTBILDNINGSOMRADE, a.UTBILDNINGSNAMN
	 HAVING (SUM(a.BEVILJADE_PLATSER_TOTALT)) > 0
ORDER BY approved_applications DESC, a.UTBILDNINGSNAMN DESC;

EXIT

