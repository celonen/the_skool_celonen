SELECT a.UTBILDNINGSNAMN AS title,
       (SUM(a.SOKTA_PLATSER_TOTALT)) -
       (SUM(a.BEVILJADE_PLATSER_TOTALT)) AS rejected_applications
FROM ANSOKAN a
	JOIN SUN5_INRIKTNING b ON b.SUN5_ID = a.SUN5_ID
	JOIN UTBILDNINGSOMRADE c ON c.UTBILDNINGSOMRADE_ID = b.UTBILDNINGSOMRADE_ID
WHERE c.UTBILDNINGSOMRADE = 'Data/IT' AND a.BESLUT = 'Avslag'
	GROUP BY a.UTBILDNINGSNAMN, c.UTBILDNINGSOMRADE
ORDER BY rejected_applications DESC, a.UTBILDNINGSNAMN DESC;

EXIT

